/**
 * Server-side lockfile probe that mirrors the client picker's detection.
 * Moved off the browser so SANDBOX_START can't race runtime resolution — the
 * caller used to fire SANDBOX_START before the client-side detection wrote
 * `runtime` back, baking a clone-only daemon whose dev server never
 * starts. Running here keeps it on the same request-lifetime as the sandbox
 * provision. On any failure we return null and the caller falls back to
 * clone-only (same behaviour as a repo with no lockfile).
 */

import type { Kysely } from "kysely";
import type { CredentialVault } from "../encryption/credential-vault";
import { getValidDownstreamAccessToken } from "../oauth/token-refresh";
import { DownstreamTokenStorage } from "../storage/downstream-token";
import type { Database } from "../storage/types";
import type { PackageManager } from "@decocms/shared/runtime-defaults";

/** Ordered: first match wins. Mirrors repository-import-picker.tsx's runtimeFiles. */
const LOCKFILES: Array<{ path: string; pm: PackageManager }> = [
  { path: "deno.json", pm: "deno" },
  { path: "deno.jsonc", pm: "deno" },
  { path: "bun.lock", pm: "bun" },
  { path: "bunfig.toml", pm: "bun" },
  { path: "pnpm-lock.yaml", pm: "pnpm" },
  { path: "yarn.lock", pm: "yarn" },
  { path: "package-lock.json", pm: "npm" },
  { path: "package.json", pm: "bun" },
];

const PORT_SOURCES: Partial<Record<PackageManager, string[]>> = {
  deno: ["deno.json", "deno.jsonc"],
  bun: ["package.json"],
  pnpm: ["package.json"],
  yarn: ["package.json"],
  npm: ["package.json"],
};

const PORT_RE = /(?:--port[=\s]*|PORT=|:)(\d{4,5})/;

export interface DetectedRuntime {
  packageManager: PackageManager;
  devPort: string | null;
}

export async function detectRepoRuntime(
  connectionId: string,
  owner: string,
  name: string,
  db: Kysely<Database>,
  vault: CredentialVault,
): Promise<DetectedRuntime | null> {
  const tokenResult = await getValidDownstreamAccessToken({
    connectionId,
    tokenStorage: new DownstreamTokenStorage(db, vault),
  });
  if (!tokenResult.accessToken) return null;
  return probeRuntime(owner, name, tokenResult.accessToken);
}

/**
 * Anonymous variant for public repos linked without a connection. Same probe,
 * no Authorization header. Hits GitHub's anon rate limit (60/h per IP) — fine
 * for one-shot detection inside SANDBOX_START, and on any failure (rate-limited,
 * network, parse) the caller falls back to clone-only just like the authed
 * path.
 */
export function detectRepoRuntimeAnonymous(
  owner: string,
  name: string,
): Promise<DetectedRuntime | null> {
  return probeRuntime(owner, name, null);
}

async function probeRuntime(
  owner: string,
  name: string,
  accessToken: string | null,
): Promise<DetectedRuntime | null> {
  // Detection runs against the repo's default branch, not the caller's sandbox
  // branch. The sandbox branch is typically a fresh name generated by SANDBOX_START
  // (e.g. `deco/keen-trail`) that hasn't been pushed yet — asking GitHub
  // for that ref 404s on every file and we'd fall back to clone-only even
  // on a valid repo. Omitting `ref` makes Contents API use HEAD.
  //
  // One listing of the root names every lockfile, so a failed request can't
  // read as a missing lockfile: SANDBOX_START probes again on every start
  // while the package manager is a detection, and a partial answer would
  // switch it.
  const root = await fetchGithubJson<Array<{ name?: unknown }>>(
    owner,
    name,
    "",
    accessToken,
  );
  if (!Array.isArray(root)) return null;
  const files = new Set(
    root.flatMap((entry) =>
      typeof entry?.name === "string" ? [entry.name] : [],
    ),
  );
  const read = (path: string) =>
    files.has(path)
      ? fetchGithubFile(owner, name, path, accessToken)
      : Promise.resolve(null);

  const deno = LOCKFILES.find(
    ({ path, pm }) => pm === "deno" && files.has(path),
  );
  const packageJson = deno ? null : await read("package.json");
  // A repo that names its package manager in package.json (corepack) is
  // installed with it, whatever lockfile history it carries.
  const declared = declaredPackageManager(packageJson);
  const hit = deno
    ? deno
    : declared
      ? { path: "package.json", pm: declared }
      : LOCKFILES.find(({ path }) => files.has(path));
  if (!hit) return null;

  let devPort: string | null = null;
  for (const path of PORT_SOURCES[hit.pm] ?? []) {
    devPort = extractDevPort(
      path === "package.json" ? packageJson : await read(path),
    );
    if (devPort) break;
  }
  return { packageManager: hit.pm, devPort };
}

const DECLARABLE: ReadonlySet<PackageManager> = new Set([
  "npm",
  "pnpm",
  "yarn",
  "bun",
]);

/** The `packageManager` field of package.json (`yarn@1.22.22` → `yarn`). */
export function declaredPackageManager(
  content: string | null,
): PackageManager | null {
  if (!content) return null;
  try {
    const field = (JSON.parse(content) as { packageManager?: unknown })
      .packageManager;
    if (typeof field !== "string") return null;
    const name = field.split("@")[0] as PackageManager;
    return DECLARABLE.has(name) ? name : null;
  } catch {
    return null;
  }
}

/**
 * 404 → null (expected: most repos won't have every lockfile). Any other
 * failure also null — a half-detected runtime is worse than clone-only,
 * since the wrong PM would hang setup.
 */
async function fetchGithubFile(
  owner: string,
  repo: string,
  path: string,
  accessToken: string | null,
): Promise<string | null> {
  const body = await fetchGithubJson<{ content?: string; encoding?: string }>(
    owner,
    repo,
    path,
    accessToken,
  );
  if (!body?.content || body.encoding !== "base64") return null;
  return Buffer.from(body.content, "base64").toString("utf8");
}

/** A Contents API response, or null on any failure. */
async function fetchGithubJson<T>(
  owner: string,
  repo: string,
  path: string,
  accessToken: string | null,
): Promise<T | null> {
  const url = `https://api.github.com/repos/${owner}/${repo}/contents/${encodeURIComponent(path)}`;
  try {
    const headers: Record<string, string> = {
      Accept: "application/vnd.github+json",
      "User-Agent": "studio-runtime-detect",
    };
    if (accessToken) headers.Authorization = `token ${accessToken}`;
    const res = await fetch(url, {
      headers,
      signal: AbortSignal.timeout(5_000),
    });
    if (!res.ok) return null;
    return (await res.json()) as T;
  } catch {
    return null;
  }
}

/**
 * `PORT_RE` allows 4-5 digits, but a 5-digit match can exceed the valid TCP
 * port range (e.g. a script's `--port 99999`, or a version-looking number the
 * regex happens to catch). The repo's `dev`/`start` script is untrusted
 * content from GitHub — bound the match to 1-65535 before it reaches
 * `start.ts`'s `Number(port)` as `devPort`, same rationale as `helpers.ts`'s
 * `parseValidPort` for the user-pinned port.
 */
export function extractDevPort(content: string | null): string | null {
  if (!content) return null;
  try {
    const parsed = JSON.parse(content) as {
      tasks?: Record<string, string>;
      scripts?: Record<string, string>;
    };
    const cmds = parsed.tasks ?? parsed.scripts ?? {};
    const cmd = cmds.dev ?? cmds.start ?? "";
    const port = cmd.match(PORT_RE)?.[1] ?? null;
    if (!port) return null;
    const n = Number(port);
    return n >= 1 && n <= 65535 ? port : null;
  } catch {
    return null;
  }
}
